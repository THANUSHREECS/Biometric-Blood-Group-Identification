"""
scripts/audit_search_05085_traceability.py
Transcription of the repository-wide search command used to audit the origin of '0.5085 Macro F1'.

PROVENANCE NOTE:
This script preserves the exact automated search protocol executed during Phase 2
to trace whether '0.5085' or '50.85' was generated by any script, notebook, log, or data file.
Confirmed finding: 'origin not traceable'. Preserved in scripts/ for full audit provenance.
"""

import os
import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

TARGET_PATTERNS = [
    re.compile(r"0\.5085"),
    re.compile(r"50\.85%?"),
]

EXTENSIONS = {".py", ".md", ".json", ".csv", ".log", ".txt", ".ipynb"}
EXCLUDE_DIRS = {".git", ".system_generated", "venv", "__pycache__", "node_modules"}

print("=" * 70)
print("AUDITING REPOSITORY FOR '0.5085' / '50.85' TRACEABILITY")
print("=" * 70)

matches = []

for root, dirs, files in os.walk(PROJECT_ROOT):
    # Filter out excluded directories
    dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS]
    
    for f in files:
        ext = os.path.splitext(f)[1].lower()
        if ext not in EXTENSIONS:
            continue
            
        file_path = Path(root) / f
        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as fp:
                for line_idx, line in enumerate(fp, 1):
                    for pat in TARGET_PATTERNS:
                        if pat.search(line):
                            rel_p = file_path.relative_to(PROJECT_ROOT)
                            matches.append((str(rel_p), line_idx, line.strip()))
        except Exception as e:
            pass

print(f"Total matching lines found across repository: {len(matches)}")
print("\nMatches found in documentation/reports:")
for p, lnum, line in matches:
    # Filter for where it appears
    print(f"  {p}:{lnum} -> {line[:100]}")

code_producing_matches = [
    (p, lnum, l) for p, lnum, l in matches 
    if p.endswith(".py") and not "leakage_audit" in p and not "provenance" in p and not "audit_" in p
]

print(f"\nMatches in candidate model generation/training code: {len(code_producing_matches)}")
if len(code_producing_matches) == 0:
    print("CONCLUSION: Origin not traceable to any pipeline, script, or logged evaluation artifact.")
