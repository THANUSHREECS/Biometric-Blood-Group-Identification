#!/usr/bin/env python3
"""
Ensemble weight search for three models (ResNet50, VGG16, EfficientNetB0).
Uses validation probability files and performs a 0.05 grid search (weights sum to 1).
Outputs full results, best weights, and a confusion matrix.
"""
import os
import sys
import time
from pathlib import Path
import numpy as np
import json
from sklearn.metrics import (
    accuracy_score,
    f1_score,
    precision_score,
    recall_score,
    confusion_matrix,
)
import matplotlib.pyplot as plt

# ---------------------------------------------------------------------------
# Ensure project root is on Python path so we can import `src` modules.
# This script lives in <project>/scripts, so two levels up is the root.
PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.config import OUTPUTS_DIR, CLASS_NAMES

# ---------------------------------------------------------------------------
# Expected probability/label files (generated by generate_validation_probs.py)
PROBS_RESNET = os.path.join(OUTPUTS_DIR, "val_probs_resnet50.npy")
PROBS_VGG = os.path.join(OUTPUTS_DIR, "val_probs_vgg16.npy")
PROBS_EFF = os.path.join(OUTPUTS_DIR, "val_probs_efficientnetb0.npy")
LABELS_PATH = os.path.join(OUTPUTS_DIR, "val_labels.npy")

# Verify existence of all required files.
for p in [PROBS_RESNET, PROBS_VGG, PROBS_EFF, LABELS_PATH]:
    if not os.path.isfile(p):
        print(f"[ERROR] Required file missing: {p}")
        sys.exit(1)

# Load probability arrays and true labels.
probs_resnet = np.load(PROBS_RESNET)
probs_vgg = np.load(PROBS_VGG)
probs_eff = np.load(PROBS_EFF)
labels = np.load(LABELS_PATH)

# Basic sanity checks.
assert probs_resnet.shape == probs_vgg.shape == probs_eff.shape, "Probability arrays shape mismatch"
assert probs_resnet.shape[0] == labels.shape[0], "Sample count mismatch"

# ---------------------------------------------------------------------------
# Grid search parameters.
STEP = 0.05
grid_vals = np.arange(0, 1 + STEP, STEP)

results = []
best = None
start_time = time.time()
MAX_SECONDS = 2 * 60 * 60  # 2‑hour guard.
combo_counter = 0

for w_resnet in grid_vals:
    for w_vgg in grid_vals:
        w_eff = round(1.0 - w_resnet - w_vgg, 10)
        # Skip invalid combos.
        if w_eff < -1e-9 or w_eff > 1:
            continue
        # Ensure w_eff aligns with the STEP grid (tolerance).
        if abs((w_eff * 100) % (STEP * 100)) > 1e-6:
            continue
        combo_counter += 1
        # Compute ensemble probabilities.
        ensemble_probs = (
            w_resnet * probs_resnet +
            w_vgg * probs_vgg +
            w_eff * probs_eff
        )
        preds = np.argmax(ensemble_probs, axis=1)
        # Metrics.
        acc = accuracy_score(labels, preds)
        macro_f1 = f1_score(labels, preds, average="macro")
        macro_prec = precision_score(labels, preds, average="macro")
        macro_rec = recall_score(labels, preds, average="macro")
        entry = {
            "w_resnet": round(w_resnet, 2),
            "w_vgg": round(w_vgg, 2),
            "w_eff": round(w_eff, 2),
            "accuracy": acc,
            "macro_f1": macro_f1,
            "macro_precision": macro_prec,
            "macro_recall": macro_rec,
        }
        results.append(entry)
        # Track best (primary macro_f1, secondary accuracy).
        if best is None or (
            macro_f1 > best["macro_f1"] or (macro_f1 == best["macro_f1"] and acc > best["accuracy"])
        ):
            best = entry
        # Runtime guard.
        if time.time() - start_time > MAX_SECONDS:
            print("[WARN] Runtime limit reached – terminating early.")
            break
    else:
        continue
    break

print(f"[INFO] Evaluated {combo_counter} weight combinations.")
print(f"[BEST] {best}")

# ---------------------------------------------------------------------------
# Persist results.
results_path = os.path.join(OUTPUTS_DIR, "three_model_ensemble_results.json")
with open(results_path, "w") as f:
    json.dump(results, f, indent=2)

weights_path = os.path.join(OUTPUTS_DIR, "three_model_ensemble_weights.json")
with open(weights_path, "w") as f:
    json.dump({
        "w_resnet": best["w_resnet"],
        "w_vgg": best["w_vgg"],
        "w_eff": best["w_eff"]
    }, f, indent=2)

# Confusion matrix for the best ensemble.
best_probs = (
    best["w_resnet"] * probs_resnet +
    best["w_vgg"] * probs_vgg +
    best["w_eff"] * probs_eff
)
best_preds = np.argmax(best_probs, axis=1)
cm = confusion_matrix(labels, best_preds)
fig, ax = plt.subplots(figsize=(6, 5))
im = ax.imshow(cm, interpolation="nearest", cmap=plt.cm.Blues)
ax.figure.colorbar(im, ax=ax)
ax.set(
    xticks=np.arange(len(CLASS_NAMES)),
    yticks=np.arange(len(CLASS_NAMES)),
    xticklabels=CLASS_NAMES,
    yticklabels=CLASS_NAMES,
    ylabel="True label",
    xlabel="Predicted label",
    title="Best Three‑Model Ensemble Confusion Matrix",
)
plt.setp(ax.get_xticklabels(), rotation=45, ha="right", rotation_mode="anchor")
threshold = cm.max() / 2.0
for i in range(cm.shape[0]):
    for j in range(cm.shape[1]):
        ax.text(j, i, format(cm[i, j], "d"), ha="center", va="center",
                color="white" if cm[i, j] > threshold else "black")
fig.tight_layout()
conf_path = os.path.join(OUTPUTS_DIR, "three_model_ensemble_confusion_matrix.png")
plt.savefig(conf_path)
plt.close()

print(f"[DONE] Full results -> {results_path}")
print(f"[DONE] Best weights -> {weights_path}")
print(f"[DONE] Confusion matrix -> {conf_path}")
